/**
 * Map a page-local path (relative to app/en, e.g. "resources/integrations/components/toolkits")
 * to its `@/components/pages/...` module path.
 */
export function pageLocalModulePath(relFromAppEn: string): string {
  const noExt = relFromAppEn.replace(/\.(tsx?|css)$/, (m) => (m === ".css" ? ".css" : ""));
  if (isToolkitOwnedLocalFile(relFromAppEn) || isToolkitOwnedLocalFile(`${relFromAppEn}.tsx`)) {
    // The toolkit workstream ports app/en/resources/integrations/components/* flat
    // into components/pages/integrations/* (e.g. components/toolkits -> toolkits).
    const rest = noExt.slice(INTEGRATIONS_REL.length + 1).replace(/^components\//, "");
    return `@/components/pages/integrations/${rest}`;
  }
  return `@/components/pages/${noExt}`;
}

/**
 * Rewrite a single import specifier found in a file that lived at
 * `app/en/<ownerRel>/<file>` (ownerRel = dir relative to app/en).
 * Returns `null` when the whole import statement must be dropped.
 */
export function rewriteSpecifier(spec: string, ownerRel: string): string | null {
  if (spec === "nextra/components") {
    return null;
  }
  if (spec === "./_meta" || spec === "./_meta.tsx") {
    return null;
  }
  let m = /^@\/app\/_components\/(.+)$/.exec(spec);
  if (m) {
    return `@/components/${m[1]}`;
  }
  m = /^@\/app\/_lib\/(.+)$/.exec(spec);
  if (m) {
    return `@/lib/${m[1]}`;
  }
  m = /^@\/app\/_data\/(.+)$/.exec(spec);
  if (m) {
    return `@/data/${m[1]}`;
  }
  m = /^(?:\.\.\/)+_components\/(.+)$/.exec(spec);
  if (m) {
    return `@/components/${m[1]}`;
  }
  m = /^(?:\.\.\/)+_lib\/(.+)$/.exec(spec);
  if (m) {
    return `@/lib/${m[1]}`;
  }
  m = /^(?:\.\.\/)+cheat-sheet-print\.css$/.exec(spec);
  if (m) {
    return "@/app/cheat-sheet-print.css";
  }
  m = /^@\/app\/en\/(.+)$/.exec(spec);
  if (m) {
    return pageLocalModulePath(m[1]);
  }
  if (spec.startsWith("./") || spec.startsWith("../")) {
    const abs = resolve("/app/en", ownerRel, spec);
    const rel = relative("/app/en", abs);
    if (!rel.startsWith("..")) {
      return pageLocalModulePath(rel);
    }
  }
  return spec;
}

