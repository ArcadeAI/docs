export type MetaEntry = {
  key: string;
  title?: string;
  icon?: string;
  href?: string;
  type?: string;
  display?: string;
  theme?: Record<string, unknown>;
};

export type EvaluatedMeta = {
  entries: MetaEntry[];
  star?: MetaEntry;
};

const JSX_MARKER = "\u0000icon=";

/** lucide-react 1.x dropped some legacy icon names used by the Nextra _meta files. */
const LUCIDE_RENAMES: Record<string, string> = { Home: "House" };

function renameLucideIcon(name: string): string {
  return LUCIDE_RENAMES[name] ?? name;
}

/**
 * Evaluate a Nextra `_meta.tsx` module with bun. JSX titles
 * (`<TitleWithIcon icon={X}>Text</TitleWithIcon>`) are turned into marker
 * strings before evaluation and split back into `title` + `icon`.
 */
export async function evaluateMeta(file: string): Promise<EvaluatedMeta> {
  let src = readFileSync(file, "utf8");
  src = src.replace(
    /<TitleWithIcon\s+icon=\{(\w+)\}>([^<]*)<\/TitleWithIcon>/g,
    (_m, icon: string, text: string) => JSON.stringify(`${text.trim()}${JSX_MARKER}${icon}`)
  );
  src = src.replace(/^import[\s\S]*?from\s+["'][^"']+["'];?[ \t]*$/gm, "");
  src = src.replace(/^function TitleWithIcon[\s\S]*?\n\}\n/m, "");
  src = src.replace(/:\s*MetaRecord\b/g, "");
  src = src.replace(/theme:\s*toolkitPageTheme\b/g, "theme: {}");

  const tmp = mkdtempSync(join(tmpdir(), "arcade-meta-"));
  const tmpFile = join(tmp, `${basename(dirname(file))}-${Date.now()}-${Math.random().toString(36).slice(2)}.ts`);
  writeFileSync(tmpFile, src);
  try {
    const mod = (await import(pathToFileURL(tmpFile).href)) as { default?: Record<string, unknown>; meta?: Record<string, unknown> };
    const raw = mod.default ?? mod.meta;
    if (!raw || typeof raw !== "object") {
      throw new Error(`No default export in ${file}`);
    }
    const result: EvaluatedMeta = { entries: [] };
    for (const [key, value] of Object.entries(raw)) {
      const entry = toMetaEntry(key, value);
      if (key === "*") {
        result.star = entry;
      } else {
        result.entries.push(entry);
      }
    }
    return result;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

function toMetaEntry(key: string, value: unknown): MetaEntry {
  const entry: MetaEntry = { key };
  const applyTitle = (t: unknown) => {
    if (typeof t !== "string") {
      return;
    }
    const idx = t.indexOf(JSX_MARKER);
    if (idx >= 0) {
      entry.title = t.slice(0, idx);
      entry.icon = renameLucideIcon(t.slice(idx + JSX_MARKER.length));
    } else {
      entry.title = t;
    }
  };
  if (typeof value === "string") {
    applyTitle(value);
    return entry;
  }
  if (value && typeof value === "object") {
    const v = value as Record<string, unknown>;
    applyTitle(v.title);
    if (typeof v.href === "string") {
      entry.href = v.href;
    }
    if (typeof v.type === "string") {
      entry.type = v.type;
    }
    if (typeof v.display === "string") {
      entry.display = v.display;
    }
    if (v.theme && typeof v.theme === "object") {
      entry.theme = v.theme as Record<string, unknown>;
    }
  }
  return entry;
}

/** Nextra theme options -> Fumadocs frontmatter additions (only non-defaults). */
export function themeToFrontmatter(theme: Record<string, unknown> | undefined): Record<string, boolean> {
  const out: Record<string, boolean> = {};
  if (!theme) {
    return out;
  }
  if (theme.layout === "full") {
    out.full = true;
  }
  if (theme.toc === false) {
    out.toc = false;
  }
  if (theme.breadcrumb === false) {
    out.breadcrumb = false;
  }
  if (theme.layout === "full" && theme.toc === false && theme.breadcrumb === false) {
    out.landing = true;
  }
  return out;
}

