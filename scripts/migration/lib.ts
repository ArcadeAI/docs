export function isToolkitIdDir(name: string): boolean {
  return name === "[toolkitId]";
}

/**
 * Page-local files under app/en that belong to the toolkit workstream
 * (ported to components/pages/integrations/** by them), relative to app/en.
 */
export function isToolkitOwnedLocalFile(rel: string): boolean {
  if (!rel.startsWith(`${INTEGRATIONS_REL}/`)) {
    return false;
  }
  const rest = rel.slice(INTEGRATIONS_REL.length + 1);
  return (
    rest.startsWith("components/") ||
    rest.startsWith("_lib/") ||
    rest === "create-category-meta.ts" ||
    rest === "toolkit-page-theme.ts" ||
    /(^|\/)\[toolkitId\]\/page-impl\.tsx$/.test(rest)
  );
}

