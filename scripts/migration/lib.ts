export type Frontmatter = { lines: string[]; end: number } | null;

/** Returns the frontmatter block (lines between the `---` fences) and the index of the first body line. */
export function splitFrontmatter(lines: string[]): { frontmatter: string[] | null; bodyStart: number } {
  if (lines[0] !== "---") {
    return { frontmatter: null, bodyStart: 0 };
  }
  const end = lines.indexOf("---", 1);
  if (end < 0) {
    return { frontmatter: null, bodyStart: 0 };
  }
  return { frontmatter: lines.slice(1, end), bodyStart: end + 1 };
}

const FENCE_RE = /^\s*(`{3,}|~{3,})/;

/**
 * Walks lines tracking fenced code blocks. `visit` receives whether the line is
 * inside a fence (fence delimiters themselves are reported with `fence: "open" | "close"`).
 */
export function forEachMdxLine(
  lines: string[],
  start: number,
  visit: (line: string, index: number, state: { inFence: boolean; fence: "open" | "close" | null }) => void
): void {
  let fence: string | null = null;
  for (let i = start; i < lines.length; i++) {
    const line = lines[i];
    const m = FENCE_RE.exec(line);
    if (fence === null && m) {
      fence = m[1];
      visit(line, i, { inFence: false, fence: "open" });
      continue;
    }
    if (fence !== null && m && m[1][0] === fence[0] && m[1].length >= fence.length && line.trim() === m[1]) {
      fence = null;
      visit(line, i, { inFence: true, fence: "close" });
      continue;
    }
    visit(line, i, { inFence: fence !== null, fence: null });
  }
}

/** Code fence meta rewrites from the plan. Applies to a fence *opening* line only. */
export function rewriteFenceMeta(line: string): string {
  const m = /^(\s*(?:`{3,}|~{3,})[^\s`~]*)(.*)$/.exec(line);
  if (!m || !m[2]) {
    return line;
  }
  let meta = m[2];
  meta = meta.replace(/\bfilename=/g, "title=");
  meta = meta.replace(/\bshowLineNumbers\b/g, "lineNumbers");
  meta = meta.replace(/\bhighlightLines=(\{[^}]*\})/g, "$1");
  return `${m[1]}${meta}`;
}

export type MdxStatement = { start: number; end: number; text: string; kind: "import" | "export" };

/** Collect MDX-level (outside code fences) import/export statements, multi-line aware. */
export function collectMdxStatements(lines: string[], start: number): MdxStatement[] {
  const out: MdxStatement[] = [];
  let open: MdxStatement | null = null;
  forEachMdxLine(lines, start, (line, i, state) => {
    if (open) {
      open.text += `\n${line}`;
      open.end = i;
      if (statementComplete(line)) {
        out.push(open);
        open = null;
      }
      return;
    }
    if (state.inFence || state.fence) {
      return;
    }
    const kind = /^import\s/.test(line) ? "import" : /^export\s/.test(line) ? "export" : null;
    if (!kind) {
      return;
    }
    const stmt: MdxStatement = { start: i, end: i, text: line, kind };
    if (kind === "import" && !statementComplete(line)) {
      open = stmt;
    } else {
      out.push(stmt);
    }
  });
  return out;
}

function statementComplete(line: string): boolean {
  return /from\s+["'][^"']+["'];?\s*$/.test(line) || /^import\s+["'][^"']+["'];?\s*$/.test(line.trim());
}

/** Is this an MDX comment line (a JSX block comment in braces) — non-content when locating the leading H1. */
function isMdxComment(line: string): boolean {
  return /^\{\/\*[\s\S]*\*\/\}\s*$/.test(line.trim());
}

/**
 * Find the leading H1: the first `# ` heading outside fences that is preceded
 * only by blank lines, import/export statements and MDX comments.
 */
export function findLeadingH1(lines: string[], start: number): { index: number; text: string } | null {
  const statements = collectMdxStatements(lines, start);
  const covered = new Set<number>();
  for (const s of statements) {
    for (let i = s.start; i <= s.end; i++) {
      covered.add(i);
    }
  }
  let result: { index: number; text: string } | null = null;
  let stop = false;
  forEachMdxLine(lines, start, (line, i, state) => {
    if (stop || result) {
      return;
    }
    if (state.inFence || state.fence) {
      stop = true;
      return;
    }
    if (covered.has(i) || line.trim() === "" || isMdxComment(line)) {
      return;
    }
    if (/^# \S/.test(line) || /^#  +\S/.test(line)) {
      result = { index: i, text: line.replace(/^#\s+/, "").trim() };
      return;
    }
    stop = true;
  });
  return result;
}

/** Remove the given statements' lines (see `removeLines`). Used by verify + migrate. */
export function removeStatementLines(lines: string[], statements: MdxStatement[]): string[] {
  const indices: number[] = [];
  for (const s of statements) {
    for (let i = s.start; i <= s.end; i++) {
      indices.push(i);
    }
  }
  return removeLines(lines, indices);
}

/**
 * Remove lines by index. When a removed line sat between two blank lines, one
 * of those blank lines is swallowed too so no double blank line is left behind.
 */
export function removeLines(lines: string[], indices: number[]): string[] {
  const drop = new Set<number>(indices);
  const out: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    if (drop.has(i)) {
      // Avoid leaving a double blank line where a statement used to be.
      const prev = out.at(-1);
      const next = lines[i + 1];
      if (prev !== undefined && prev.trim() === "" && next !== undefined && next.trim() === "" && !drop.has(i + 1)) {
        i++; // swallow the following blank line
      }
      continue;
    }
    out.push(lines[i]);
  }
  return out;
}

export function stripSubpageListMetaProp(line: string): string {
  if (!line.includes("<SubpageList")) {
    return line;
  }
  return line.replace(/\s+meta=\{meta\}/, "");
}

