export type SourceDir = {
  /** Path relative to app/en ("" for app/en itself). */
  rel: string;
  abs: string;
  name: string;
  hasPage: boolean;
  metaFile: string | null;
  children: SourceDir[];
  /** Page-local files (tsx/ts/css) that sit beside page.mdx and are ours to copy. */
  localFiles: string[];
};

export function readSourceTree(sourceRoot: string): SourceDir {
  const appEn = join(sourceRoot, "app", "en");

  function walk(abs: string, rel: string): SourceDir | null {
    const entries = readdirSync(abs, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
    const dir: SourceDir = {
      rel,
      abs,
      name: basename(abs),
      hasPage: false,
      metaFile: null,
      children: [],
      localFiles: [],
    };
    for (const e of entries) {
      const childRel = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) {
        if (isToolkitIdDir(e.name)) {
          continue;
        }
        if (isToolkitOwnedLocalFile(`${childRel}/x`)) {
          // components/ and _lib/ under resources/integrations
          continue;
        }
        const child = walk(join(abs, e.name), childRel);
        if (child) {
          dir.children.push(child);
        }
        continue;
      }
      if (e.name === "page.mdx") {
        dir.hasPage = true;
      } else if (e.name === "_meta.tsx") {
        dir.metaFile = join(abs, e.name);
      } else if (/\.(tsx?|css)$/.test(e.name)) {
        if (!isToolkitOwnedLocalFile(childRel)) {
          dir.localFiles.push(e.name);
        }
      }
    }
    // Drop directories that contribute nothing (e.g. a category folder that only
    // held [toolkitId]) unless they carry a _meta.tsx (they still produce a folder).
    if (!(dir.hasPage || dir.metaFile || dir.children.length || dir.localFiles.length)) {
      return null;
    }
    return dir;
  }

  const root = walk(appEn, "");
  if (!root) {
    throw new Error("app/en is empty");
  }
  return root;
}

/** Whether a source directory becomes a folder in content/docs (vs. a leaf .mdx). */
export function isFolder(dir: SourceDir): boolean {
  if (dir.rel === "") {
    return true;
  }
  return dir.children.length > 0 || (dir.metaFile !== null && !dir.hasPage);
}

export function* iterateDirs(dir: SourceDir): Generator<SourceDir> {
  yield dir;
  for (const c of dir.children) {
    yield* iterateDirs(c);
  }
}

/** Target MDX path (relative to content/docs) for a source dir that has page.mdx. */
export function targetMdxRel(dir: SourceDir): string {
  if (dir.rel === "") {
    return "index.mdx";
  }
  return isFolder(dir) ? `${dir.rel}/index.mdx` : `${dir.rel}.mdx`;
}

